// Builds index.html: joins the files in src/ and inlines a compiled Tailwind stylesheet,
// so the game works offline and loads without the Tailwind CDN.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const parts = ['1-layout.html', '2-data.js', '3-events.js', '4-logic.js'];
const game = parts.map(f => fs.readFileSync(path.join(__dirname, 'src', f), 'utf8')).join('\n');

fs.mkdirSync(path.join(__dirname, 'build'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'build', 'game.html'), game);

execFileSync(path.join(__dirname, 'node_modules', '.bin', 'tailwindcss'),
  ['-c', 'tailwind.config.js', '-i', 'src/tailwind.css', '-o', 'build/tailwind.css', '--minify'],
  { cwd: __dirname, stdio: 'inherit' });

const css = fs.readFileSync(path.join(__dirname, 'build', 'tailwind.css'), 'utf8');
const out = game.replace(/<!-- TAILWIND:START -->[\s\S]*<!-- TAILWIND:END -->/,
  `<!-- TAILWIND:START (generated by build.js, do not edit) -->\n  <style>${css}</style>\n  <!-- TAILWIND:END -->`);
fs.writeFileSync(path.join(__dirname, 'index.html'), out);
console.log(`index.html written (${Math.round(out.length / 1024)} KB)`);
